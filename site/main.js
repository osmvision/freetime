function storedLang() {
  try {
    return localStorage.getItem('freetime.site.lang');
  } catch {
    return null;
  }
}

function setLang(lang) {
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    el.dataset.en ??= el.textContent;
    el.textContent = lang === 'fr' ? (FR[el.dataset.en] ?? el.dataset.en) : el.dataset.en;
  }
  // Idea titles in the tape carry their own French.
  for (const el of document.querySelectorAll('[data-fr]')) {
    el.dataset.en ??= el.textContent;
    el.textContent = lang === 'fr' ? el.dataset.fr : el.dataset.en;
  }
  // App screenshots in the same language (and the theme follows the system, see <source>).
  const fr = lang === 'fr' ? '-fr' : '';
  for (const pic of document.querySelectorAll('picture[data-shot]')) {
    const name = pic.dataset.shot;
    pic.querySelector('source').srcset = `img/app-${name}${fr}-dark.webp`;
    pic.querySelector('img').src = `img/app-${name}${fr}.webp`;
  }
  for (const img of document.querySelectorAll('img[data-night]')) img.src = `img/app-night${fr}.webp`;
  for (const img of document.querySelectorAll('img[data-feat]')) img.src = `img/feat-${img.dataset.feat}${fr}.webp`;
  const btn = document.querySelector('.lang');
  if (btn) {
    btn.textContent = lang === 'fr' ? 'EN' : 'FR';
    btn.setAttribute('aria-label', lang === 'fr' ? 'Switch to English' : 'Passer en français');
  }
}

let lang = storedLang() ?? (navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en');
if (lang !== 'en') setLang(lang);
document.querySelector('.lang')?.addEventListener('click', () => {
  lang = lang === 'fr' ? 'en' : 'fr';
  setLang(lang);
  try {
    localStorage.setItem('freetime.site.lang', lang);
  } catch {
    // Private window: the choice just isn't remembered.
  }
});

// The tape is printed twice so it loops without a gap.
const track = document.querySelector('.tape-track');
if (track) {
  for (const node of [...track.children]) {
    const copy = node.cloneNode(true);
    copy.setAttribute('aria-hidden', 'true');
    track.append(copy);
  }
}

// Point the download buttons at the latest installer itself. If GitHub can't be reached,
// they keep pointing at the releases page, which works too.
fetch('https://api.github.com/repos/osmvision/freetime/releases/latest', { headers: { Accept: 'application/vnd.github+json' } })
  .then((r) => (r.ok ? r.json() : null))
  .then((release) => {
    const asset = release?.assets?.find((a) => /-setup\.exe$/i.test(a.name));
    if (!asset) return;
    for (const a of document.querySelectorAll('.js-download')) a.href = asset.browser_download_url;
    for (const v of document.querySelectorAll('.js-version')) v.textContent = release.tag_name;
  })
  .catch(() => {});
