// Copies the fonts and icons the UI uses from node_modules into ui/, so the app ships them
// itself (strict CSP, works offline). Run after changing the lists below:
//   node scripts/vendor-assets.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mods = join(root, 'node_modules');

const FONTS = [
  ['@fontsource/barlow-condensed', 'barlow-condensed-latin-500-normal.woff2'],
  ['@fontsource/barlow-condensed', 'barlow-condensed-latin-600-normal.woff2'],
  ['@fontsource/barlow-condensed', 'barlow-condensed-latin-700-normal.woff2'],
  ['@fontsource/barlow-condensed', 'barlow-condensed-latin-800-normal.woff2'],
  ['@fontsource/barlow', 'barlow-latin-400-normal.woff2'],
  ['@fontsource/barlow', 'barlow-latin-500-normal.woff2'],
  ['@fontsource/barlow', 'barlow-latin-600-normal.woff2'],
  ['@fontsource/barlow', 'barlow-latin-700-normal.woff2'],
  ['@fontsource/courier-prime', 'courier-prime-latin-400-normal.woff2'],
  ['@fontsource/courier-prime', 'courier-prime-latin-700-normal.woff2'],
];

const ICONS = [
  // navigation and actions
  'compass', 'history', 'sliders-horizontal', 'ticket', 'play', 'x', 'check', 'chevron-down', 'shuffle',
  'refresh-cw', 'map-pin', 'thumbs-up', 'thumbs-down', 'external-link', 'search', 'folder-open',
  'key-round', 'trash-2', 'info', 'triangle-alert', 'loader-circle', 'bookmark', 'arrow-right', 'copy', 'user-plus', 'message-circle', 'send', 'ban', 'user-x',
  'user-check', 'pencil', 'log-out', 'log-in', 'chevron-left', 'flag', 'download', 'shield',
  // context
  'clock', 'zap', 'battery-low', 'battery-medium', 'battery-full', 'user', 'users', 'sun', 'house',
  'wallet', 'heart', 'tree-pine',
  // weather
  'cloud-sun', 'cloud', 'cloud-rain', 'cloud-fog', 'cloud-lightning', 'snowflake', 'moon', 'wind',
  // categories
  'gamepad-2', 'circle-play', 'activity', 'graduation-cap', 'palette', 'leaf', 'utensils',
  // avatars (see ui/js/avatars.js)
  'rocket', 'ghost', 'cat', 'dog', 'crown', 'star', 'flame', 'mountain', 'bike', 'coffee', 'pizza',
  'music', 'trophy', 'sword', 'dice-5', 'skull',
];

mkdirSync(join(root, 'ui', 'fonts'), { recursive: true });
for (const [pkg, file] of FONTS) {
  copyFileSync(join(mods, pkg, 'files', file), join(root, 'ui', 'fonts', file));
}

const out = {};
const missing = [];
for (const name of ICONS) {
  const file = join(mods, 'lucide-static', 'icons', `${name}.svg`);
  if (!existsSync(file)) {
    missing.push(name);
    continue;
  }
  const svg = readFileSync(file, 'utf8');
  out[name] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
if (missing.length) {
  console.error('missing icons:', missing.join(', '));
  process.exit(1);
}

const version = JSON.parse(readFileSync(join(mods, 'lucide-static', 'package.json'), 'utf8')).version;
writeFileSync(
  join(root, 'ui', 'js', 'icons.js'),
  `// Generated by scripts/vendor-assets.mjs from lucide-static ${version} (ISC license, lucide.dev).\n` +
    `// Static, trusted markup: the only HTML the UI ever injects.\n` +
    `export const ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')};\n`,
);
console.log(`fonts: ${FONTS.length}, icons: ${Object.keys(out).length} (lucide ${version})`);
